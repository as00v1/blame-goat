/** 渲染区块：把 {{key}} 替换为参数值 */
export function renderBlock(text, params) {
  return text.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    const v = params[key];
    return v === undefined ? `{{${key}}}` : String(v);
  });
}

/** System Prompt 区块顺序（v2.4：evaluation 紧跟在评分维度之后） */
export const BLOCK_ORDER = [
  'data_note', 'mode_context', 'scoring', 'evaluation',
  'labels', 'constraints', 'output_format', 'insight_rule', 'cast_rule',
];

/** 组装 System Prompt（区块 1-9） */
export function buildSystemPrompt(params = DEFAULT_PARAMS) {
  const p = { ...DEFAULT_PARAMS, ...params };
  return BLOCK_ORDER.map((k) => renderBlock(BLOCKS[k], p)).join('\n\n');
}

