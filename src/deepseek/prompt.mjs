/**
 * 喂给模型前的 dataset 投影 —— 只处理「界面要、模型不该看到」的字段。
 *
 * ① 出装 / 符文的图标路径（`items[].icon`、`augments[].icon`）：
 *    实测占 8322 字 ≈ 5200 tokens，是整次请求的约 20%，而模型一个字都用不上
 *    —— 它既不是判断依据，又给了模型一个「编造未提供信息」的诱因。
 *    名字（中文名）保留，那才是提示词【多维评估要求】要模型读的东西。
 *
 * ② 阵营编号（`teamId` / `myTeamId` / `winningTeam`，值是 LCU 内部的 100 / 200）：
 *    这两个数字对模型毫无意义，它却会照抄进报告 —— 真机出过「100队…200队…」这种
 *    机器味的句子。这里统一换成 side / winningSide：「我方」或「敌方」。
 *    阵营归属本身必须留着（isMyTeam），模型要靠它分清哪边输了。
 *
 * 不改原对象：dataset 还要落盘给界面用，图标与 teamId 都必须留在里面。
 */
export function modelDataset(dataset) {
  if (!dataset?.players) return dataset;

  const myTeamId = dataset.match?.myTeamId ?? null;
  const sideOf = (teamId) => {
    if (teamId == null || myTeamId == null) return '未知阵营';
    return teamId === myTeamId ? '我方' : '敌方';
  };
  const withoutTeamId = ({ teamId, ...rest }) => rest;

  return {
    ...dataset,
    match: withoutTeamId(dataset.match || {}),
    teams: (dataset.teams || []).map((t) => ({ ...withoutTeamId(t), side: sideOf(t.teamId) })),
    players: dataset.players.map((p) => ({
      ...withoutTeamId(p),
      items: (p.items || []).map(({ icon, ...rest }) => rest),
      augments: (p.augments || []).map(({ icon, ...rest }) => rest),
    })),
    timeline: (dataset.timeline || []).map((e) => {
      if (e.winningTeam == null) return e;
      const { winningTeam, ...rest } = e;
      return { ...rest, winningSide: sideOf(winningTeam) };
    }),
  };
}

/** 组装 User 消息（区块 9） */
export function buildUserMessage(dataset, tone = 'normal', params = DEFAULT_PARAMS) {
  const p = { ...DEFAULT_PARAMS, ...params };
  return renderBlock(BLOCKS.user_template, p)
    .replace('{{tone}}', TONES[tone] || TONES.normal)
    .replace('{{dataset}}', JSON.stringify(modelDataset(dataset), null, 2));
}

/** 供界面「提示词」页预览用：返回完整消息对 */
export function buildMessages(dataset, tone = 'normal', params = DEFAULT_PARAMS) {
  return [
    { role: 'system', content: buildSystemPrompt(params) },
    { role: 'user', content: buildUserMessage(dataset, tone, params) },
  ];
}

/** 统计：区块字数 / 估算 token（中文约 1.6 字/token） */
export function promptStats(params = DEFAULT_PARAMS) {
  const system = buildSystemPrompt(params);
  return {
    chars: system.length,
    estTokens: Math.round(system.length / 1.6),
    blocks: Object.keys(BLOCKS).length,
    params: Object.keys(DEFAULT_PARAMS).length,
  };
}
